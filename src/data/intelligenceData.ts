/**
 * Filter health insights by profile, time range, and optional category
 */
export function getHealthInsights(
  profileId: string,
  timeRange: TimeRangeFilter = '30d',
  category?: InsightCategory | 'all'
): HealthInsight[] {
  return demoHealthInsights.filter((ins) => {
    if (ins.profileId !== profileId) return false;
    if (!ins.timeRange.includes(timeRange)) return false;
    if (category && category !== 'all' && ins.category !== category) return false;
    return true;
  });
}

