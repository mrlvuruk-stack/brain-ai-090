export function getHealthPatterns(profileId: string): HealthPattern[] {
  return demoHealthPatterns.filter((pat) => pat.profileId === profileId);
}

/**
 * Retrieve health summary for profile and timeRange
 */
export function getHealthSummary(
  profileId: string,
  timeRange: TimeRangeFilter = '30d'
): HealthSummaryData {
  const profileSummaries = demoHealthSummaries[profileId] || demoHealthSummaries.aarav;
  return profileSummaries[timeRange] || profileSummaries['30d'];
}

/**
 * Retrieve intelligence activities for profile
 */
export function getIntelligenceActivity(profileId: string): IntelligenceActivityItem[] {
  return demoIntelligenceActivities[profileId] || demoIntelligenceActivities.aarav;
}

/**
 * Return 2-3 featured insights for the Prototype Overview Dashboard
 */
export function getDashboardFeaturedInsights(profileId: string): HealthInsight[] {
  const all = demoHealthInsights.filter((ins) => ins.profileId === profileId);
  return all.slice(0, 3);
}
